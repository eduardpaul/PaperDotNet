#!/usr/bin/env bash
# Runs the permission queries through the real ListsDbContext (EF Core 10, both providers) on the benchmark data.
# Needs the .NET 10 SDK, psql and python3; PostgreSQL through the PG* variables (a database "efprobe" is created).
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${OUT:-$HERE/out}
mkdir -p "$OUT"
PGCS="Host=${PGHOST:-localhost};Port=${PGPORT:-5432};Username=${PGUSER:-postgres};Database=efprobe${PGPASSWORD:+;Password=$PGPASSWORD}"
SQLITECS="Data Source=$OUT/probe.db"

main() {
dotnet build "$HERE/EfProbe.csproj" -c Release -v q -o "$OUT/bin" > /dev/null
probe() { dotnet "$OUT/bin/EfProbe.dll" "$@"; }

echo "== SQL generated by EF Core"
probe sql sqlite "$SQLITECS"
probe sql postgresql "$PGCS"

echo "== data in EF's schema"
psql -X -q -c 'DROP DATABASE IF EXISTS efprobe' -c 'CREATE DATABASE efprobe'
psql -X -q -v ON_ERROR_STOP=1 -d efprobe -f "$HERE/../pg/01_data.sql" 2>/dev/null
psql -X -q -d efprobe -c 'ALTER SCHEMA bench RENAME TO lists'
probe ddl sqlite "$SQLITECS" > "$OUT/ddl_sqlite.sql"
psql -X -q -d efprobe -c "\\copy (SELECT upper(id::text), upper(tenant_id::text), upper(list_id::text), upper(content_type_id::text), upper(parent_id::text), is_folder::int, has_unique_permissions::int, upper(scope_id::text), title, fields::text, 0, upper(created_by::text), 0, upper(updated_by::text), NULL, NULL, version FROM lists.items) TO '$OUT/items.csv' WITH (FORMAT csv)"
psql -X -q -d efprobe -c "\\copy (SELECT upper(id::text), upper(tenant_id::text), upper(list_id::text), upper(object_id::text), principal_type, upper(principal_id::text), level FROM lists.permission_grants) TO '$OUT/grants.csv' WITH (FORMAT csv)"
python3 "$HERE/sqlite_from_pg.py" "$OUT/ddl_sqlite.sql" "$OUT/items.csv" "$OUT/grants.csv" "$OUT/probe.db"
rm -f "$OUT/items.csv" "$OUT/grants.csv"

echo "== today (ADR-0011 as implemented)"
for p in sqlite postgresql; do
  cs=$([ $p = sqlite ] && echo "$SQLITECS" || echo "$PGCS")
  probe run $p "$cs"
  probe opens $p "$cs"
done

echo "== option A"
psql -X -q -d efprobe -f "$HERE/option_a.sql"
python3 - "$OUT/probe.db" <<'PY'
import hashlib, sqlite3, sys
g = lambda s: (lambda h: f'{h[:8]}-{h[8:12]}-{h[12:16]}-{h[16:20]}-{h[20:]}'.upper())(hashlib.md5(s.encode()).hexdigest())
db = sqlite3.connect(sys.argv[1])
db.execute('UPDATE lists_items SET scope_id = list_id WHERE scope_id IS NULL')
for (l,) in db.execute('SELECT DISTINCT list_id FROM lists_items').fetchall():
    db.execute('INSERT INTO lists_permission_grants VALUES (?,?,?,?,?,?,?)', (g('ws' + l.lower()), g('tenant'), l, l, 'Group', g('ws-members'), 'Contribute'))
db.executescript('''DROP INDEX ix_lists_items_list_id_scope_id;
CREATE INDEX ix_items_scope_id_id ON lists_items(scope_id, id);
CREATE INDEX ix_grants_principal ON lists_permission_grants(principal_id, list_id, object_id);
ANALYZE;''')
db.commit()
PY
for p in sqlite postgresql; do
  cs=$([ $p = sqlite ] && echo "$SQLITECS" || echo "$PGCS")
  probe runA $p "$cs"
  probe runJson $p "$cs"
done
}

main 2>&1 | tee "$OUT/log.txt"
grep '^@@' "$OUT/log.txt" > "$OUT/results.txt"
echo "== done: $OUT/results.txt"
