# Regenerate row mappings only after reviewing a reference upgrade. Runtime SQL copies are pinned in source.
import argparse
import base64
import hashlib
import json
import pathlib
import re
import sqlite3
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("papergo", type=pathlib.Path)
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parents[2]
go = args.papergo.resolve()
out = root / "src/BuildingBlocks/PaperDotNet.Content"
(out / "Generated").mkdir(parents=True, exist_ok=True)
manifest = json.loads((root / "tools/papergo/reference.json").read_text())
commit = subprocess.check_output(
    ["git", "-C", str(go), "rev-parse", "HEAD"], text=True
).strip()
if commit != manifest["commit"]:
    raise SystemExit(
        "Reference checkout differs from the pinned commit; review the manifest first."
    )
sql = (go / "internal/dal/schema/sqlite.sql").read_text()
pg = (go / "internal/dal/schema/postgres.sql").read_text()
for provider, source in [("sqlite", sql), ("postgresql", pg)]:
    actual = base64.b64encode(hashlib.sha256(source.encode()).digest()).decode()
    if actual != manifest["schemas"][provider]["sha256Base64"]:
        raise SystemExit("Schema fingerprint differs from the reviewed reference.")
db = sqlite3.connect(":memory:")
db.executescript(sql)
names = {
    t[0]: "".join(x.title() for x in t[0].split("_")) + "Row"
    for t in db.execute(
        "select name from sqlite_master where type='table' and name not like 'sqlite_%'"
    )
}


def prop(n):
    return "".join(x.title() for x in n.split("_"))


pgcols = {}
for t, body in re.findall(r"CREATE TABLE (\w+) \((.*?)\n\);", pg, re.DOTALL):
    pgcols[t] = {
        n: typ
        for n, typ in re.findall(
            r'^    "?(\w+)"? (\w+(?:\(\d+, ?\d+\))?)', body, re.MULTILINE
        )
    }
model = [
    "// <auto-generated />",
    "#nullable enable",
    "using Microsoft.EntityFrameworkCore;",
    "namespace PaperDotNet.Content;",
    "public abstract partial class ContentDbContext",
    "{",
    "    private static void ConfigureRows(ModelBuilder model)",
    "    {",
]
for t, cls in names.items():
    cols = list(db.execute(f'pragma table_info("{t}")'))
    lines = [
        "// <auto-generated />",
        "#nullable enable",
        "namespace PaperDotNet.Content;",
        f"public sealed class {cls}",
        "{",
    ]
    model += [
        f"        model.Entity<{cls}>(e =>",
        "        {",
        f'            e.ToTable("{t}");',
    ]
    keys = [prop(c[1]) for c in sorted(cols, key=lambda c: c[5]) if c[5]]
    model += [
        "            e.HasKey(x => "
        + (
            "x." + keys[0]
            if len(keys) == 1
            else "new { " + ", ".join("x." + k for k in keys) + " }"
        )
        + ");"
    ]
    for _, n, st, nn, default, pk in cols:
        pt = pgcols[t][n]
        nullable = not (nn or pk)
        typ = {
            "BYTEA": "byte[]",
            "TEXT": "string",
            "TIMESTAMPTZ": "DateTime",
            "BOOLEAN": "bool",
            "BIGINT": "long",
            "INTEGER": "long",
            "JSONB": "string",
            "NUMERIC(38, 9)": "decimal",
            "NUMERIC(38,9)": "decimal",
        }.get(pt)
        if typ is None:
            raise ValueError(f"Unsupported reference column: {t}.{n} ({pt})")
        d = ""
        if default is not None:
            if default == "CURRENT_TIMESTAMP":
                d = "DateTime.UtcNow"
            elif typ == "bool":
                d = "true" if default.upper() in ("TRUE", "1") else "false"
            elif typ == "string":
                d = json.dumps(default.strip("'").replace("''", "'"))
            elif typ in ("long", "decimal"):
                d = default + ("m" if typ == "decimal" else "")
        if not d and not nullable and typ == "string":
            d = "string.Empty"
        if not d and not nullable and typ == "byte[]":
            d = "[]"
        lines += [
            f"    public {typ}{'?' if nullable else ''} {prop(n)} {{ get; set; }}"
            + (" = " + d + ";" if d else "")
        ]
        conf = f'            e.Property(x => x.{prop(n)}).HasColumnName("{n}").ValueGeneratedNever()'
        if not nullable and typ == "string":
            conf += ".IsRequired()"
        if n == "version" or t == "live_change_position" and n == "position":
            conf += ".IsConcurrencyToken()"
        model += [conf + ";"]
    # navigation-free FKs allow EF to order inserts and fix up conceptual relationships.
    fks = {}
    for fk in db.execute(f'pragma foreign_key_list("{t}")'):
        fks.setdefault(fk[0], []).append(fk)
    for group in fks.values():
        group.sort(key=lambda fk: fk[1])
        target = group[0][2]
        action = group[0][6]
        behavior = {
            "CASCADE": "Cascade",
            "SET NULL": "SetNull",
            "RESTRICT": "Restrict",
            "NO ACTION": "NoAction",
        }[action]
        cols_expr = (
            "x." + prop(group[0][3])
            if len(group) == 1
            else "new { " + ", ".join("x." + prop(f[3]) for f in group) + " }"
        )
        model += [
            f"            e.HasOne<{names[target]}>().WithMany().HasForeignKey(x => {cols_expr}).OnDelete(DeleteBehavior.{behavior});"
        ]
    lines += ["}"]
    (out / "Generated" / f"{cls}.cs").write_text("\n".join(lines) + "\n")
    model += ["        });"]
model += ["    }", "}"]
(out / "Generated/ContentDbContext.Rows.cs").write_text("\n".join(model) + "\n")
# Provider-specific types and timestamp converters stay in provider assemblies.
for provider, source in [("Sqlite", sql), ("PostgreSql", pg)]:
    p = root / f"src/BuildingBlocks/PaperDotNet.Persistence.{provider}/Content"
    p.mkdir(exist_ok=True)
    (p / "PaperGo.sql").write_text(source)
    conf = [
        "// <auto-generated />",
        "#nullable enable",
        "using Microsoft.EntityFrameworkCore;",
        "using PaperDotNet.Content;",
        f"namespace PaperDotNet.Persistence.{provider}.Content;",
        f"public sealed partial class {provider}ContentDbContext",
        "{",
        "    protected override void OnModelCreating(ModelBuilder model)",
        "    {",
        "        base.OnModelCreating(model);",
    ]
    if provider == "Sqlite":
        conf += [
            "        var converter = new Microsoft.EntityFrameworkCore.Storage.ValueConversion.ValueConverter<DateTime, string>(",
            "            value => PaperGoTimestamp.Format(value), value => PaperGoTimestamp.Parse(value));",
        ]
    for t, cls in names.items():
        for n, pt in pgcols[t].items():
            if n not in [c[1] for c in db.execute(f'pragma table_info("{t}")')]:
                continue
            if provider == "Sqlite" and pt == "TIMESTAMPTZ":
                conf += [
                    f"        model.Entity<{cls}>().Property(x => x.{prop(n)}).HasConversion(converter);"
                ]
            elif provider == "PostgreSql":
                conf += [
                    f'        model.Entity<{cls}>().Property(x => x.{prop(n)}).HasColumnType("{pt.lower()}");'
                ]
    conf += ["    }", "}"]
    (p / f"{provider}ContentDbContext.Model.cs").write_text("\n".join(conf) + "\n")
print(len(names), "tables generated")
